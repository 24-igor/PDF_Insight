const DEFAULT_LANGUAGE = 'pl'

/**
 * Detect the predominant natural language of document text using ISO 639-1 codes.
 *
 * Heuristics (no external NLP dependency):
 * 1. Character script detection (Cyrillic → ru, CJK → ja/zh/ko, etc.)
 * 2. Stop-word frequency scoring across supported European languages
 * 3. Token filtering to skip numbers, URLs, all-caps tokens, and technical noise
 *
 * Excluded from language determination: UI language, user location, filename,
 * company/personal names, addresses, isolated foreign phrases, technical terms.
 *
 * Falls back to DEFAULT_LANGUAGE ('pl') when no signal is found.
 */
export function detectLanguage(text: string): string {
  if (!text || text.trim().length === 0) return DEFAULT_LANGUAGE

  // 1. Character script detection (strong signal for non-Latin scripts)
  if (/[\u0400-\u04FF]/.test(text)) return 'ru' // Cyrillic
  if (/[\u3040-\u309F\u30A0-\u30FF]/.test(text)) return 'ja' // Japanese
  if (/[\uAC00-\uD7AF]/.test(text)) return 'ko' // Korean
  if (/[\u4E00-\u9FFF]/.test(text)) return 'zh' // Chinese (Han)

  // 2. Tokenize: extract word-like characters including common European diacritics
  const tokens =
    text.toLowerCase().match(/[a-zà-ÿäëïöüâêîôûãõñçąćęłńóśźżßæøåðþšžčđ]+/g) ??
    []

  if (tokens.length === 0) return DEFAULT_LANGUAGE

  // Filter: keep meaningful word-length tokens, skip noise
  const meaningfulTokens = tokens.filter(
    (t) => t.length >= 2 && t.length <= 20 && !/^\d+$/.test(t),
  )

  if (meaningfulTokens.length === 0) return DEFAULT_LANGUAGE

  // 3. Score each language by stop-word matches
  const scores: Record<string, number> = {}
  for (const [lang, stopWords] of Object.entries(STOP_WORDS)) {
    let score = 0
    for (const token of meaningfulTokens) {
      if (stopWords.has(token)) score += 1
    }
    scores[lang] = score
  }

  // 4. Pick the highest scorer; fallback if no matches
  let bestLang = DEFAULT_LANGUAGE
  let bestScore = 0
  for (const [lang, score] of Object.entries(scores)) {
    if (score > bestScore) {
      bestScore = score
      bestLang = lang
    }
  }

  return bestScore === 0 ? DEFAULT_LANGUAGE : bestLang
}
